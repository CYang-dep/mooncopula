"""Reproduce committed test vectors from external mathematical libraries.
Run with Python 3.12 and scripts/oracle-requirements.txt. No production dependency.
"""
import argparse
from pathlib import Path
import numpy as np
from scipy.stats import rankdata, kendalltau, spearmanr, kstest, cramervonmises
from scipy.optimize import minimize_scalar
from statsmodels.distributions.copula.api import ClaytonCopula, FrankCopula, GumbelCopula
from decimal import Decimal, localcontext

ROOT = Path(__file__).resolve().parents[1]
def number(x):
    value = float(x)
    if not np.isfinite(value):
        raise ValueError(f"nonfinite reference {x}")
    text = repr(value)
    if 'e' in text and '.' not in text.split('e')[0]:
        text = text.replace('e', '.0e')
    return text
def frank_decimal(t, u, v):
    with localcontext() as ctx:
        ctx.prec = 80
        t,u,v = map(lambda x: Decimal(str(x)), (t,u,v))
        a,b,d = (-t*u).exp()-1, (-t*v).exp()-1, (-t).exp()-1
        den=d+a*b
        return -(den/d).ln()/t, (-t*d)*(-t*(u+v)).exp()/(den*den), (-t*u).exp()*b/den

def generate():
    lines=['// Generated by scripts/generate_oracle.py; test data, not production code.', '///|', 'test "external statsmodels and decimal analytic reference vectors" {']
    for name,cls,params in [('Clayton',ClaytonCopula,[.01,.5,2.,30.]),('Gumbel',GumbelCopula,[1.01,2.,20.]),('Frank',FrankCopula,[-30.,-2.,-.01,.01,2.,30.])]:
        for theta in params:
            for u,v in [(.1,.8),(.3,.7),(.55,.65),(.93,.97)]:
                model=cls(theta)
                cdf=float(np.asarray(model.cdf([u,v])).item())
                pdf=float(np.asarray(model.pdf([u,v])).item())
                conditional=None
                if name=='Frank':
                    cdf,pdf,conditional=map(float,frank_decimal(theta,u,v))
                lines += [f'  let c = Copula::new({name}, {number(theta)})',f'  close(c.cdf({u}, {v}), {number(cdf)}, 2.0e-9)',f'  close(c.log_density({u}, {v}), {number(np.log(pdf))}, 2.0e-8)']
                if conditional is not None:
                    lines += [f'  close(c.conditional({u}, {v}), {number(conditional)}, 2.0e-8)']
    lines+=['}', '///|', 'test "high precision Frank boundary vectors" {']
    for theta in [-30.,-.01,.01,30.]:
        for u,v in [(1e-10,2e-10),(1-1e-10,1-2e-10),(.5,1-1e-10)]:
            cdf,pdf,h=frank_decimal(theta,u,v)
            lines += [f'  let c = Copula::new(Frank, {theta})',f'  close(c.cdf({number(u)}, {number(v)}), {number(cdf)}, 2.0e-9)',f'  close(c.log_density({number(u)}, {number(v)}), {number(float(pdf.ln()))}, 2.0e-8)',f'  close(c.conditional({number(u)}, {number(v)}), {number(h)}, 2.0e-8)']
    lines+=['}', '///|', 'test "SciPy independent ranks concordance and uniformity" {']
    x=[8.,2.,2.,5.,9.,1.]; y=[3.,4.,4.,2.,8.,7.]
    data=', '.join(f'{{x: {a}, y: {b}}}' for a,b in zip(x,y))
    lines += [f'  let raw = [{data}]',f'  close(concordance(raw).tau_b, {number(kendalltau(x,y).statistic)}, 1.0e-13)',f'  close(spearman(raw), {number(spearmanr(x,y).statistic)}, 1.0e-13)']
    for i,r in enumerate(rankdata(x)):
        lines += [f'  close(ranks(raw.map(fn(p) {{p.x}}))[{i}], {number(r / (len(x)+1))}, 1.0e-13)']
    vals=[.03,.12,.4,.42,.8,.93]
    lines += [f'  let d = uniform_diagnostic({vals})',f'  close(d.ks_distance, {number(kstest(vals,"uniform").statistic)}, 1.0e-13)',f'  close(d.cramer_von_mises, {number(cramervonmises(vals,"uniform").statistic)}, 1.0e-13)', '}']
    # Fixed external observations; independently maximize statsmodels likelihood.
    rng=np.random.default_rng(20261111)
    data=ClaytonCopula(2.).rvs(80, random_state=rng)
    result=minimize_scalar(lambda t: -float(ClaytonCopula(t).logpdf(data).sum()), bounds=(.01,30), method='bounded', options={'xatol':1e-9})
    lines+=['///|','test "pseudo likelihood matches SciPy optimized statsmodels density" {','  let data = [']
    lines += [f'    {{x: {number(a)}, y: {number(b)}}},' for a,b in data]
    lines += ['  ]','  let result = fit(Clayton, data)',f'  close(result.model.theta, {number(result.x)}, 2.0e-5)',f'  close(result.log_likelihood, {number(-result.fun)}, 1.0e-8)','}']
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    path=ROOT/'oracle_wbtest.mbt'; result=generate()
    if args.check:
        # moon fmt may wrap lines: compare whitespace-insensitively.
        if ''.join(path.read_text(encoding='utf-8').replace(',', '').split()) != ''.join(result.replace(',', '').split()):
            raise SystemExit('oracle fixture drift; regenerate then moon fmt')
        print('independent oracle fixture verified')
    else:
        path.write_text(result, encoding='utf-8')


